/** Is Obsidian's language Chinese? Read at call time, not when this module loads. */
function useChinese(): boolean {
  try {
    const locale: unknown = typeof moment?.locale === 'function' ? moment.locale() : '';
    return typeof locale === 'string' && locale.toLowerCase().startsWith('zh');
  } catch {
    return false;
  }
}

export function tr(key: StringKey, vars?: Record<string, string | number>): string {
  const template = (useChinese() ? zh[key] : undefined) ?? en[key] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match);
}
