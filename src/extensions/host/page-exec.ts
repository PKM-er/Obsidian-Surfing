// In Chrome, a USER_SCRIPT world configured with 'unsafe-inline'
// (userScripts.configureWorld) inserts inline <script>s that run in the page
// even when the page's own CSP forbids inline code: the world's CSP applies
// instead. Electron's extension worlds have no such override, so on strict
// pages (greasyfork.org, github.com, …) Tampermonkey's page bridge and
// window.external.Tampermonkey never appear.
//
// A session preload restores it: it listens for a secret DOM event from the
// user script world and runs the code with webFrame.executeJavaScript, which
// executes synchronously in the main world and is exempt from the page CSP.
// The event is cancelable, so the sender knows whether the preload ran it.
import * as fs from 'node:fs';
import { runInlineScript } from '../shared/inline-script';
import type * as Electron from 'electron';

export const PAGE_EXEC_PRELOAD_ID = 'obsidian-chrome-bridge-page-exec';

/** Event names carry a per-vault secret: page scripts cannot use the CSP exemption. */
export function pageExecEvent(secret: string): string {
  return '__obsidian_bridge_exec_' + secret;
}

/** The preload's source (Electron sandboxed preload: only `require('electron')`). */
export function pageExecPreload(eventName: string): string {
  return `'use strict';
// Generated by Obsidian Chrome Bridge: runs inline scripts from extension user
// script worlds despite the page CSP (Chrome's userScripts world CSP).
(() => {
  const { webFrame } = require('electron');
  const run = ${runInlineScript.toString()};
  const warn = e => console.warn('[Chrome Bridge] page exec:', e);
  document.addEventListener(${JSON.stringify(eventName)}, event => {
    if (typeof event.detail !== 'string') return;
    let message;
    try { message = JSON.parse(event.detail); } catch { return; }
    if (!message || typeof message.code !== 'string') return;
    event.stopImmediatePropagation();
    event.preventDefault();
    try {
      // executeJavaScript itself is exempt from the page CSP; a <script>
      // element it inserted would not be. Code for a same-origin child frame
      // still goes through an element there (and that frame's CSP applies).
      const source = typeof message.frame === 'string' ? '(' + run + ')(' + JSON.stringify(event.detail) + ')' : message.code;
      Promise.resolve(webFrame.executeJavaScript(source)).catch(warn);
    } catch (e) { warn(e); }
  }, true);
})();
`;
}

/** Registers the preload on a session; returns false where Electron cannot. */
export function installPageExec(ses: Electron.Session, file: string, eventName: string): boolean {
  if (typeof ses?.registerPreloadScript !== 'function') return false;
  const source = pageExecPreload(eventName);
  let current: string | null = null;
  try { current = fs.readFileSync(file, 'utf8'); } catch { /* best effort */ }
  if (current !== source) fs.writeFileSync(file, source);
  uninstallPageExec(ses);
  ses.registerPreloadScript({ type: 'frame', id: PAGE_EXEC_PRELOAD_ID, filePath: file });
  return true;
}

export function uninstallPageExec(ses: Electron.Session | null | undefined): void {
  try { ses?.unregisterPreloadScript?.(PAGE_EXEC_PRELOAD_ID); } catch { /* best effort */ }
}
